#!/usr/bin/env python3
"""build_shaders.py - resolve GLSL includes, compile with glslang, embed SPIR-V into a C++ header.

The shipped executable carries its shaders as embedded SPIR-V, which is what keeps the deliverable
to "one exe + one .pak": no shader sources, no compiler, no DLLs at runtime. The .pak may still
override a stage with its own shaders/<name>.spv, so shaders stay hot-swappable without a rebuild.
"""
import argparse
import os
import re
import struct
import subprocess
import sys

STAGES = [
    ("main.rgen", "kRaygen"),
    ("hit.rchit", "kClosestHit"),
    ("shadow_hit.rchit", "kShadowHit"),
    ("miss.rmiss", "kMiss"),
    ("shadow_miss.rmiss", "kShadowMiss"),
    ("present.vert", "kPresentVert"),
    ("present.frag", "kPresentFrag"),
    ("fallback.comp", "kFallbackComp"),
]

INCLUDE_RE = re.compile(r'^\s*#include\s+"([^"]+)"\s*$')


def flatten(shader_dir, filename, seen, out, is_root):
    """Textually inline `filename` into `out`. Nested #includes expand in place, depth-first."""
    full = os.path.normpath(os.path.join(shader_dir, filename))
    key = full.lower()
    if key in seen:
        return
    seen.add(key)
    if not os.path.isfile(full):
        raise SystemExit("error: missing include %s" % full)
    with open(full, "r", encoding="utf-8") as f:
        text = f.read()

    out.append("// ---- begin %s ----" % filename)
    for line in text.splitlines():
        m = INCLUDE_RE.match(line)
        if m:
            flatten(shader_dir, m.group(1), seen, out, False)
            continue
        if not is_root and line.strip().startswith("#version"):
            continue  # only the root file's #version may survive
        out.append(line)
    out.append("// ---- end %s ----" % filename)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--shaders", default="shaders")
    ap.add_argument("--glslang", required=True)
    ap.add_argument("--out-dir", default="build/glsl")
    ap.add_argument("--header", default="src/generated/shaders_spv.h")
    ap.add_argument("--target-env", default="vulkan1.3")
    args = ap.parse_args()

    os.makedirs(args.out_dir, exist_ok=True)
    os.makedirs(os.path.dirname(args.header), exist_ok=True)

    glslang = os.path.abspath(args.glslang)
    if not os.path.isfile(glslang):
        print("error: glslang not found at %s" % glslang, file=sys.stderr)
        return 2

    compiled = []
    failures = 0
    for filename, ident in STAGES:
        src = os.path.join(args.shaders, filename)
        if not os.path.isfile(src):
            print("error: missing shader %s" % src, file=sys.stderr)
            failures += 1
            continue
        lines = []
        flatten(args.shaders, filename, set(), lines, True)
        flat_path = os.path.join(args.out_dir, filename)
        with open(flat_path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")

        spv_path = os.path.join(args.out_dir, os.path.splitext(filename)[0] + ".spv")
        proc = subprocess.run([glslang, "-V", "--target-env", args.target_env, "-O",
                               "-e", "main", "-o", spv_path, flat_path],
                              capture_output=True, text=True)
        if proc.returncode != 0:
            failures += 1
            print("=== %s FAILED ===" % filename)
            print((proc.stdout or "") + (proc.stderr or ""))
            continue
        with open(spv_path, "rb") as f:
            blob = f.read()
        if len(blob) % 4:
            print("error: %s is not a SPIR-V module" % spv_path, file=sys.stderr)
            failures += 1
            continue
        words = struct.unpack("<%dI" % (len(blob) // 4), blob)
        compiled.append((ident, words))
        print("  %-22s -> %6d bytes (%d words)" % (filename, len(blob), len(words)))

    if failures:
        print("error: %d shader(s) failed to compile" % failures, file=sys.stderr)
        return 1

    with open(args.header, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/build_shaders.py - do not edit.\n")
        f.write("#pragma once\n#include <cstddef>\n#include <cstdint>\n\nnamespace shaders {\n\n")
        for ident, words in compiled:
            f.write("static const std::uint32_t %s[] = {\n" % ident)
            for i in range(0, len(words), 12):
                f.write("    " + ", ".join("0x%08X" % w for w in words[i:i + 12]) + ",\n")
            f.write("};\n")
            f.write("static const std::size_t %sWords = sizeof(%s) / sizeof(std::uint32_t);\n\n"
                    % (ident, ident))
        f.write("}  // namespace shaders\n")

    print("wrote %s" % args.header)
    return 0


if __name__ == "__main__":
    sys.exit(main())
